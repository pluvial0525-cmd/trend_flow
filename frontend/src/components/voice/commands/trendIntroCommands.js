// =========================================================
// Trend Intro Page Voice Commands
//
// 현재 페이지:
// /trend-intro
//
// 중요:
// 이 파일의 명령은 다른 페이지로 이동시키지 않는다.
// 현재 TrendIntroPage 내부 상태만 변경한다.
//
// 단, 시뮬레이션처럼 명확한 페이지 이동 명령은
// 별도의 navigation 명령으로 반환한다.
// =========================================================


// =========================================================
// 텍스트 정리
// =========================================================

function normalize(text = "") {

    return text
        .trim()
        .toLowerCase()
        .replace(/[.,!?~]/g, "")
        .replace(/\s+/g, " ");
}


// =========================================================
// 단어 포함 확인
// =========================================================

function includesAny(
    text,
    words
) {

    return words.some(
        (word) =>
            text.includes(word)
    );
}


// =========================================================
// Trend Intro 명령 분석
// =========================================================

export function detectTrendIntroCommand(
    rawText = ""
) {

    const text =
        normalize(rawText);


    // =====================================================
    // 1. 전체 그래프
    // =====================================================

    if (
        includesAny(
            text,
            [
                "전체",
                "모두",
                "전부",
                "전체 그래프",
                "전체 비교",
                "다 보여",
            ]
        )
    ) {

        return {
            type: "SELECT_TREND",
            trend: null,
        };
    }


    // =====================================================
    // 2. 스키니진
    // =====================================================

    if (
        includesAny(
            text,
            [
                "스키니진",
                "스키니 진",
                "스키니",
            ]
        )
    ) {

        return {
            type: "SELECT_TREND",
            trend: "skinny",
        };
    }


    // =====================================================
    // 3. 떡볶이 코트
    // =====================================================

    if (
        includesAny(
            text,
            [
                "떡볶이 코트",
                "떡볶이코트",

                "떡볶 코트",
                "떡볶코트",

                "떡볶이 코드",
                "떡볶이코드",

                "떡볶 코드",
                "떡볶코드",

                "더플 코트",
                "더플코트",
                "더플",
            ]
        )
    ) {

        return {
            type: "SELECT_TREND",
            trend: "duffle",
        };
    }


    // =====================================================
    // 4. 어그부츠
    // =====================================================

    if (
        includesAny(
            text,
            [
                "어그부츠",
                "어그 부츠",
                "어그",
            ]
        )
    ) {

        return {
            type: "SELECT_TREND",
            trend: "ugg",
        };
    }


    // =====================================================
    // 5. 로우라이즈
    // =====================================================

    if (
        includesAny(
            text,
            [
                "로우라이즈",
                "로우 라이즈",
                "로라이즈",
                "로우라이즈 팬츠",
            ]
        )
    ) {

        return {
            type: "SELECT_TREND",
            trend: "lowrise",
        };
    }


    // =====================================================
    // 6. 벨루어 트랙수트
    // =====================================================

    if (
        includesAny(
            text,
            [
                "벨루어 트랙수트",
                "벨루어트랙수트",
                "벨루어",
                "트랙수트",
                "트랙 수트",
            ]
        )
    ) {

        return {
            type: "SELECT_TREND",
            trend: "velour",
        };
    }


    // =====================================================
    // 7. 시뮬레이션
    //
    // 이 명령만 페이지 이동 허용
    // =====================================================

    const simulationTarget =
        includesAny(
            text,
            [
                "시뮬레이션",
                "시물레이션",
                "시뮬레이터",
            ]
        );


    const navigationIntent =
        includesAny(
            text,
            [
                "넘어가",
                "이동",
                "열어",
                "가줘",
                "가자",
                "보여줘",
                "보여 줘",
            ]
        );


    if (
        simulationTarget
        &&
        navigationIntent
    ) {

        return {
            type: "NAVIGATE",
            path: "/trend-city",
        };
    }


    // =====================================================
    // 아무 명령도 아님
    // =====================================================

    return null;
}