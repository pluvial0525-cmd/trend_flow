import {
    correctVoiceCommand,
} from "./voiceUtils";


// =========================================================
// GLOBAL COMMAND DETECTOR
// =========================================================

export function detectGlobalCommand(
    command = ""
) {

    const text =
        correctVoiceCommand(
            command
        );


    console.log(
        "[VOICE CORRECTED]",
        text
    );


    if (!text) {
        return null;
    }


    // =====================================================
    // GraphRAG
    // =====================================================

    if (
        text.includes(
            "graphrag"
        )
    ) {

        return {
            type:
                "GO_GRAPHRAG",
        };
    }


    // =====================================================
    // 시뮬레이션
    // =====================================================

    if (
        text.includes(
            "시뮬레이션"
        )
    ) {

        return {
            type:
                "GO_SIMULATION",
        };
    }


    // =====================================================
    // PCA
    // =====================================================

    if (
        text.includes(
            "pca"
        )
    ) {

        return {
            type:
                "GO_PCA",
        };
    }


    // =====================================================
    // Trend Flow
    // =====================================================

    if (
        text.includes(
            "트렌드 플로우"
        )
    ) {

        return {
            type:
                "GO_TREND_FLOW",
        };
    }


    // =====================================================
    // 스키니진
    // =====================================================

    if (
        text.includes(
            "스키니진"
        )
    ) {

        return {
            type:
                "GO_SKINNY",
        };
    }


    // =====================================================
    // 어그
    // =====================================================

    if (
        text.includes(
            "어그"
        )
    ) {

        return {
            type:
                "GO_UGG",
        };
    }


    // =====================================================
    // 로우라이즈
    // =====================================================

    if (
        text.includes(
            "로우라이즈"
        )
    ) {

        return {
            type:
                "GO_LOW_RISE",
        };
    }


    // =====================================================
    // 떡볶이 코트
    // =====================================================

    if (
        text.includes(
            "떡볶이 코트"
        )
    ) {

        return {
            type:
                "GO_DUFFLE",
        };
    }


    // =====================================================
    // 벨루어
    // =====================================================

    if (
        text.includes(
            "벨루어"
        )
    ) {

        return {
            type:
                "GO_VELOUR",
        };
    }


    // =====================================================
    // Cypher
    // =====================================================

    if (
        text.includes(
            "cypher"
        )
        ||
        text.includes(
            "사이퍼"
        )
    ) {

        return {
            type:
                "GO_CYPHER",
        };
    }


    // =====================================================
    // 중심성
    // =====================================================

    if (
        text.includes(
            "중심성"
        )
    ) {

        return {
            type:
                "GO_CENTRALITY",
        };
    }


    // =====================================================
    // RDB vs Graph
    // =====================================================

    if (
        (
            text.includes(
                "rdb"
            )
            ||
            text.includes(
                "관계형"
            )
        )
        &&
        (
            text.includes(
                "graph"
            )
            ||
            text.includes(
                "그래프"
            )
        )
    ) {

        return {
            type:
                "GO_RDB_VS_GRAPH",
        };
    }


    // =====================================================
    // GraphDB 구조
    // =====================================================

    if (
        text.includes(
            "graphdb"
        )
        ||
        text.includes(
            "그래프 데이터베이스"
        )
    ) {

        return {
            type:
                "GO_GRAPH_STRUCTURE",
        };
    }


    // =====================================================
    // 처음으로
    // =====================================================

    if (
        text.includes(
            "처음"
        )
        ||
        text.includes(
            "첫 화면"
        )
    ) {

        return {
            type:
                "GO_HOME",
        };
    }


    // =====================================================
    // 이전
    // =====================================================

    if (
        text.includes(
            "이전"
        )
        ||
        text.includes(
            "뒤로"
        )
    ) {

        return {
            type:
                "PREVIOUS_PAGE",
        };
    }


    // =====================================================
    // 다음
    // =====================================================

    if (
        text.includes(
            "다음"
        )
    ) {

        return {
            type:
                "NEXT_PAGE",
        };
    }


    // =====================================================
    // 발표 시작
    //
    // 가장 마지막에 검사
    // 다른 명령에 "시작"이라는 단어가 들어가도
    // START로 잘못 잡는 것을 줄임
    // =====================================================

    if (
        text.includes(
            "시작"
        )
    ) {

        return {
            type:
                "START_PRESENTATION",
        };
    }


    return null;
}