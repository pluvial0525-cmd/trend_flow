// =========================================================
// WAKE WORDS
//
// 실제 호출어: "콩"
//
// Whisper가 실제 테스트에서
// "콩" → "퐁"으로 인식한 경우가 있어서
// "퐁"까지만 허용
//
// "공"은 일반 발표에서 나올 수 있으므로 제외
// =========================================================

const WAKE_WORDS = [
    "콩",
    "퐁",
];


// =========================================================
// 기본 문자열 정리
// =========================================================

export function normalizeVoiceText(
    text = ""
) {

    return String(text)
        .trim()
        .toLowerCase()

        .replace(
            /[.,!?~"'`…]/g,
            " "
        )

        .replace(
            /\s+/g,
            " "
        )

        .trim();
}


// =========================================================
// 단어 배열
// =========================================================

function getWords(
    text = ""
) {

    const normalized =
        normalizeVoiceText(
            text
        );


    if (!normalized) {
        return [];
    }


    return normalized
        .split(" ")
        .filter(Boolean);
}


// =========================================================
// 호출어 위치 찾기
// =========================================================

function findWakeWordIndex(
    text = ""
) {

    const words =
        getWords(
            text
        );


    return words.findIndex(
        (word) =>
            WAKE_WORDS.includes(
                word
            )
    );
}


// =========================================================
// 호출어 포함 여부
//
// O
// 콩
// 아 콩
// 네 콩
// 콩 시작해줘
// 아 콩 스키니진 보여줘
//
// X
// 콩나물
// 성공
// 공
// =========================================================

export function hasWakeWord(
    text = ""
) {

    return (
        findWakeWordIndex(
            text
        )
        !== -1
    );
}


// =========================================================
// 호출어 이후 명령 추출
//
// "콩"
// → ""
//
// "아 콩"
// → ""
//
// "콩 시작해줘"
// → "시작해줘"
//
// "네 콩 스키니진 보여줘"
// → "스키니진 보여줘"
// =========================================================

export function extractVoiceCommand(
    text = ""
) {

    const words =
        getWords(
            text
        );


    const wakeIndex =
        words.findIndex(
            (word) =>
                WAKE_WORDS.includes(
                    word
                )
        );


    if (
        wakeIndex === -1
    ) {

        return normalizeVoiceText(
            text
        );
    }


    return words
        .slice(
            wakeIndex + 1
        )
        .join(" ")
        .trim();
}


// =========================================================
// Whisper 명령 보정
// =========================================================

export function correctVoiceCommand(
    text = ""
) {

    let corrected =
        normalizeVoiceText(
            text
        );


    // =====================================================
    // 시뮬레이션
    // =====================================================

    corrected =
        corrected.replace(
            /시뮬에이션|시물레이션|시뮬래이션|시뮬에이텬|시뮬에이선|시뮬레이숀|시물레션/g,
            "시뮬레이션"
        );


    // =====================================================
    // PCA
    // =====================================================

    corrected =
        corrected.replace(
            /피씨에이|피시에이|피시 에이|피씨 에이|p c a/g,
            "pca"
        );


    // =====================================================
    // GraphRAG
    // =====================================================

    corrected =
        corrected.replace(
            /그래프랙|그래프 랙|그래프래그|그래프 래그|그라프랙|그라프래그/g,
            "graphrag"
        );


    // =====================================================
    // Neo4j
    // =====================================================

    corrected =
        corrected.replace(
            /네오포제이|네오포제|네오 포 제이|니오포제이|니오 포 제이/g,
            "neo4j"
        );


    // =====================================================
    // Cypher
    // =====================================================

    corrected =
        corrected.replace(
            /싸이퍼|사이프|사이퍼문/g,
            "cypher"
        );


    // =====================================================
    // GraphDB
    // =====================================================

    corrected =
        corrected.replace(
            /그래프 디비|그래프디비|그래프 db/g,
            "graphdb"
        );


    // =====================================================
    // RDB
    // =====================================================

    corrected =
        corrected.replace(
            /알디비|아르디비|r d b/g,
            "rdb"
        );


    // =====================================================
    // Trend Flow
    // =====================================================

    corrected =
        corrected.replace(
            /트렌드 플로|트랜드 플로우|트렌드플로우|트렌드 흐름/g,
            "트렌드 플로우"
        );


    // =====================================================
    // Skinny Jeans
    // =====================================================

    corrected =
        corrected.replace(
            /스키니 진|스키니진즈|스키니 팬츠/g,
            "스키니진"
        );


    // =====================================================
    // Low Rise
    // =====================================================

    corrected =
        corrected.replace(
            /로우 라이즈|로우라이즈 팬츠|로라이즈/g,
            "로우라이즈"
        );


    // =====================================================
    // UGG
    // =====================================================

    corrected =
        corrected.replace(
            /어그 부츠|어그부츠|ugg 부츠/g,
            "어그"
        );


    // =====================================================
    // Duffle
    // =====================================================

    corrected =
        corrected.replace(
            /떡볶 코트|떡볶코트|떡볶이코드|떡볶 코드|떡볶코드|더플 코트|더플코트/g,
            "떡볶이 코트"
        );


    // =====================================================
    // Velour
    // =====================================================

    corrected =
        corrected.replace(
            /벨벳 트레이닝복|벨벳 츄리닝|벨루어 트레이닝복/g,
            "벨루어"
        );


    // =====================================================
    // Centrality
    // =====================================================

    corrected =
        corrected.replace(
            /센트럴리티|센트럴리티이|중심성 분석/g,
            "중심성"
        );


    return corrected
        .replace(
            /\s+/g,
            " "
        )
        .trim();
}